-- Jalankan di Supabase SQL Editor setelah tabel pelanggan, produk_jasa,
-- dan transaksi sudah tersedia.
-- Aman dijalankan ulang: tidak menghapus data yang sudah ada.

BEGIN;

CREATE TABLE IF NOT EXISTS public.karyawan (
    id_karyawan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_karyawan VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20),
    jabatan VARCHAR(50) NOT NULL
);

ALTER TABLE public.transaksi
    ADD COLUMN IF NOT EXISTS id_karyawan INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_transaksi_karyawan'
          AND conrelid = 'public.transaksi'::regclass
    ) THEN
        ALTER TABLE public.transaksi
            ADD CONSTRAINT fk_transaksi_karyawan
            FOREIGN KEY (id_karyawan)
            REFERENCES public.karyawan (id_karyawan)
            ON DELETE RESTRICT;
    END IF;
END
$$;

ALTER TABLE public.karyawan ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'karyawan'
          AND policyname = 'karyawan_read_write'
    ) THEN
        CREATE POLICY "karyawan_read_write" ON public.karyawan
            FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    END IF;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.karyawan TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.karyawan_id_karyawan_seq TO anon, authenticated;

COMMIT;

INSERT INTO public.karyawan (nama_karyawan, no_hp, jabatan)
SELECT sample.nama_karyawan, sample.no_hp, sample.jabatan
FROM (VALUES
    ('Andi Saputra', '087700000001', 'Teknisi'),
    ('Siti Rahma', '087700000002', 'Kasir'),
    ('Budi Santoso', '087700000003', 'Admin')
) AS sample(nama_karyawan, no_hp, jabatan)
WHERE NOT EXISTS (
    SELECT 1
    FROM public.karyawan AS existing
    WHERE existing.no_hp = sample.no_hp
);

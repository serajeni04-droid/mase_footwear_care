-- Skema lengkap MASE Footwear Care untuk PostgreSQL / Supabase.
-- Aman dijalankan ulang: tabel, relasi, kebijakan, dan data seed tidak digandakan.

BEGIN;

CREATE TABLE IF NOT EXISTS public.pelanggan (
    id_pelanggan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pelanggan VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS public.produk_jasa (
    id_item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_item VARCHAR(100) NOT NULL,
    jenis_item VARCHAR(20) NOT NULL CHECK (jenis_item IN ('Jasa', 'Produk')),
    harga NUMERIC(12,2) NOT NULL DEFAULT 0,
    stok INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.karyawan (
    id_karyawan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_karyawan VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20),
    jabatan VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.transaksi (
    id_transaksi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal_transaksi DATE NOT NULL DEFAULT CURRENT_DATE,
    id_pelanggan INTEGER NOT NULL,
    id_item INTEGER NOT NULL,
    id_karyawan INTEGER,
    jumlah INTEGER NOT NULL CHECK (jumlah > 0),
    total_harga NUMERIC(12,2) NOT NULL,
    metode_pembayaran VARCHAR(20) NOT NULL CHECK (metode_pembayaran IN ('CASH', 'QRIS', 'TRANSFER'))
);

ALTER TABLE public.transaksi
    ADD COLUMN IF NOT EXISTS id_karyawan INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_transaksi_pelanggan'
          AND conrelid = 'public.transaksi'::regclass
    ) THEN
        ALTER TABLE public.transaksi
            ADD CONSTRAINT fk_transaksi_pelanggan
            FOREIGN KEY (id_pelanggan)
            REFERENCES public.pelanggan (id_pelanggan)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_transaksi_item'
          AND conrelid = 'public.transaksi'::regclass
    ) THEN
        ALTER TABLE public.transaksi
            ADD CONSTRAINT fk_transaksi_item
            FOREIGN KEY (id_item)
            REFERENCES public.produk_jasa (id_item)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_transaksi_karyawan'
          AND conrelid = 'public.transaksi'::regclass
    ) THEN
        ALTER TABLE public.transaksi
            ADD CONSTRAINT fk_transaksi_karyawan
            FOREIGN KEY (id_karyawan)
            REFERENCES public.karyawan (id_karyawan)
            ON DELETE RESTRICT;
    END IF;
END
$$;

ALTER TABLE public.pelanggan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.produk_jasa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.karyawan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transaksi ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'pelanggan' AND policyname = 'pelanggan_read_write') THEN
        CREATE POLICY "pelanggan_read_write" ON public.pelanggan
            FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'produk_jasa' AND policyname = 'produk_jasa_read_write') THEN
        CREATE POLICY "produk_jasa_read_write" ON public.produk_jasa
            FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'karyawan' AND policyname = 'karyawan_read_write') THEN
        CREATE POLICY "karyawan_read_write" ON public.karyawan
            FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'transaksi' AND policyname = 'transaksi_read_write') THEN
        CREATE POLICY "transaksi_read_write" ON public.transaksi
            FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.pelanggan, public.produk_jasa, public.karyawan, public.transaksi TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.pelanggan_id_pelanggan_seq, public.produk_jasa_id_item_seq, public.karyawan_id_karyawan_seq, public.transaksi_id_transaksi_seq TO anon, authenticated;

